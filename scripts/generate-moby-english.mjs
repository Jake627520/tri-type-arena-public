// Rebuild the English typing pool from Grady Ward's Moby Words II frequency list.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const input = readFileSync(new URL('./data/moby-freq.txt', import.meta.url));
const checksum = createHash('sha256').update(input).digest('hex');
if (checksum !== 'ace4ecc06acf0d3df397cf4d680d0d9c7a308e4860c10eb9b9edf2f4e31076c9') throw new Error('Unexpected Moby source checksum.');
const seen = new Set();
const words = input.toString('ascii').split(/\r?\n/).slice(1).map((raw) => raw.trim()).filter((raw) => /^[A-Za-z]+$/.test(raw)).map((raw) => raw.toLowerCase()).filter((word) => {
  if (seen.has(word)) return false;
  seen.add(word);
  return true;
});
const tiers = [
  { id: 'beg', difficulty: 'beginner', words: words.filter((word) => word.length >= 2 && word.length <= 4).slice(0, 200), expected: 200 },
  { id: 'int', difficulty: 'intermediate', words: words.filter((word) => word.length >= 5 && word.length <= 6).slice(0, 200), expected: 200 },
  { id: 'adv', difficulty: 'advanced', words: words.filter((word) => word.length >= 7).slice(0, 100), expected: 100 },
];
const entries = tiers.flatMap((tier) => {
  if (tier.words.length !== tier.expected) throw new Error(`Not enough words for ${tier.id}`);
  return tier.words.map((word, index) => ({ id: `en-moby-${tier.id}-${String(index + 1).padStart(3, '0')}`, mode: 'en', display: word, answer: word, hint: word, difficulty: tier.difficulty, category: 'common' }));
});
const out = `import { VocabularyEntry } from "./types";\n\n// Generated by scripts/generate-moby-english.mjs; source and terms: docs/vocabulary/MOBY_ENGLISH.md.\nexport const ENGLISH_VOCABULARY: readonly VocabularyEntry[] = Object.freeze([\n${entries.map((entry) => `  ${JSON.stringify(entry)},`).join('\n')}\n]);\n`;
const destination = new URL('../src/domain/vocabulary/en.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== out) throw new Error('Generated English vocabulary differs from source.');
  console.log('English vocabulary matches the pinned Moby source.');
} else {
  writeFileSync(destination, out);
}
