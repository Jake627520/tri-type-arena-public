// Generate the legacy JavaScript engine's small pool from the current candidate data.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pools = {};
for (const [mode, file] of [['en', 'en'], ['pinyin', 'pinyin'], ['zhuyin', 'zhuyin']]) {
  const source = readFileSync(resolve(root, `src/domain/vocabulary/${file}.ts`), 'utf8');
  const entries = source.split('\n').filter(line => line.trim().startsWith('{"')).map(line => JSON.parse(line.trim().replace(/,$/, '')));
  if (entries.length < 12) throw new Error(`Insufficient ${mode} entries`);
  pools[mode] = entries.slice(0, 12).map(({ display, answer, hint }) => ({ display, answer, hint }));
}
const output = '// Generated by scripts/generate-legacy-lessons.mjs from the current candidate vocabulary.\nexport const LESSONS = ' + JSON.stringify(pools, null, 2) + ';\n';
const path = resolve(root, 'src/legacy-lessons.mjs');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Legacy lessons differ from current vocabulary');
} else writeFileSync(path, output);
